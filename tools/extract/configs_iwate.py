def _config(
    *,
    year: int,
    question: int,
    grade: int,
    field: str,
    detail_unit: str,
    filename: str,
    stamp: str,
    problem: list[dict],
    answer_box: list[int],
    answers: list[dict],
    explanation: list[dict],
    problem_page_groups: list[list[int]] | None = None,
    science_dpi: int | None = None,
) -> dict:
    answer_scale, answer_scale_label = _ANSWER_SCALES[year]
    config = {
        "slug": f"iwate_q{question}_{year}",
        "repo": "koukou-nyushi-iwate",
        "year": year,
        "prefecture": "岩手県",
        "question": question,
        "question_label": f"大問{question}",
        "grade": grade,
        "field": field,
        "detail_unit": detail_unit,
        "filename": filename,
        "stamp": stamp,
        "science_ref": _SCIENCE_REFS[year],
        **_SOURCES[year],
        "problem": problem,
        "answer_scale": answer_scale,
        "answer_scale_label": answer_scale_label,
        "answer_sheet": [
            {
                "page": 1,
                "box": answer_box,
                "source_ref_size": [1075, 1518],
                "rotation": 0,
            }
        ],
        "answers": answers,
        "explanation": explanation,
        **({"science_dpi": science_dpi} if science_dpi is not None else {}),
    }
    if problem_page_groups is not None:
        config["problem_page_groups"] = problem_page_groups
    return config


